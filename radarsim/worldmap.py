class WorldMap:
    def __init__(self, rect):
        self.rect = r = pygame.Rect(rect)
        self.base = pygame.Surface(r.size)
        self.base.fill((8, 20, 34))
        for poly in LAND:
            pts = [self._p(la, lo) for lo, la in poly]
            pygame.draw.polygon(self.base, (38, 58, 46), pts)
            pygame.draw.polygon(self.base, (74, 104, 84), pts, 1)
        for lo in range(-180, 181, 30):
            x = self._p(0, lo)[0]
            pygame.draw.line(self.base, (22, 40, 58), (x, 0), (x, r.h), 1)
            if -180 < lo < 180:
                text(self.base, "%d%s" % (abs(lo), "E" if lo > 0 else ("W" if lo < 0 else "")), (x + 2, r.h - 13), 9, (70, 96, 120))
        for la in range(-60, 61, 30):
            y = self._p(la, 0)[1]
            pygame.draw.line(self.base, (22, 40, 58) if la else (40, 66, 92), (0, y), (r.w, y), 1)
            text(self.base, "%d%s" % (abs(la), "N" if la > 0 else ("S" if la < 0 else "")), (2, y + 1), 9, (70, 96, 120))

    def _p(self, lat, lon):
        return ((lon + 180) / 360.0 * self.rect.w, (90 - lat) / 180.0 * self.rect.h)

    def xy(self, lat, lon):
        x, y = self._p(lat, lon)
        return self.rect.x + x, self.rect.y + y

    def latlon(self, pos):
        return (90 - (pos[1] - self.rect.y) / self.rect.h * 180.0,
                (pos[0] - self.rect.x) / self.rect.w * 360.0 - 180.0)

    def draw(self, s):
        s.blit(self.base, self.rect)
        pygame.draw.rect(s, C["edge"], self.rect, 1)

    def footprint(self, s, lat, lon, ang, color, step=4, size=1):
        """Dotted circle of angular radius `ang` degrees around a sub-point."""
        for b in range(0, 360, step):
            la, lo = gc_dest(lat, lon, b, ang)
            pygame.draw.circle(s, color, self.xy(la, lo), size)

    def marker(self, s, lat, lon, color, label=None, kind="dot", size=5):
        x, y = self.xy(lat, lon)
        if kind == "dot":
            pygame.draw.circle(s, color, (x, y), size)
            pygame.draw.circle(s, (0, 0, 0), (x, y), size, 1)
        elif kind == "sq":
            pygame.draw.rect(s, color, (x - size, y - size, 2 * size, 2 * size))
        elif kind == "tri":
            pygame.draw.polygon(s, color, [(x, y - size - 1), (x + size, y + size), (x - size, y + size)])
        else:
            pygame.draw.line(s, color, (x - size, y - size), (x + size, y + size), 2)
            pygame.draw.line(s, color, (x - size, y + size), (x + size, y - size), 2)
        if label:
            text(s, label, (x + size + 3, y - 6), 10, color, bold=True)
        return x, y
